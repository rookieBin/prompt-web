import { BaseAgent } from './BaseAgent';

export class JudgeAgent extends BaseAgent {
  protected getSystemPrompt(): string {
    return `你是一个提示词评审官。请用简洁自然语言给出评分和建议，适合直接显示在控制台。

要求：
1. 评分维度：清晰度、完整性、可用性，满分100。直接写成“清晰度：85；完整性：70；可用性：80”。
2. 紧接着用一句“综合得分：XX/100（通过/未通过）”。通过条件：综合得分≥80。
3. 提供 1-2 句反馈，说明主要问题和亮点。
4. 最后给出一句“建议：……”总结改进方向。
5. 全部输出使用纯文本，禁止 JSON / Markdown 标题 / 列表符号。

示例（仅供参考）：
清晰度：82；完整性：60；可用性：68
综合得分：70/100（未通过）
反馈：提示词能概述目标，但缺少输入约束与角色分工。执行步骤过于笼统，缺乏具体指令。
建议：补充目标用户、关键场景以及需要强调的数据或输出格式，使可执行度提升。

请按上述格式输出。`;
  }
}
